"""Generate copy for manual LinkedIn review from the canonical portfolio data."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render_profile(data, variants):
    personal = data["personal"]
    software = variants["variants"]["software_platform"]
    current = next(role for role in data["experience"] if role["id"] == "exp-stellantis")
    achievements = {item["id"]: item["text"] for item in current["achievements"]}
    experience = "\n".join(
        f"- {achievements[key]}" for key in software["experienceAchievementIds"][current["id"]]
    )
    projects = {item["id"]: item for item in data["projects"]}
    featured = "\n".join(
        f'- [{projects[key]["name"]}]({projects[key]["link"]})'
        for key in software["projectIds"]
    )
    canonical = data["seo"]["canonicalUrl"].rstrip("/") + "/"
    return f"""<!-- Generated by scripts/generate_linkedin_profile.py. -->
# LinkedIn profile for {personal['name']}

## Headline

{personal['title']} | Developer Productivity | Internal Tools | Secure Delivery Automation

Use this headline by default. It identifies the software you build and the engineers it serves while leaving your official title in Experience.

### Alternatives

- Software Engineer | Internal Tools, APIs & Workflow Automation
- Developer Productivity & Platform Software | Tooling, CI/CD & Release Automation
- Security Automation Engineer | Secrets Discovery, Application Authorization & Secure CI/CD

## About

{data['about']}

## Current Experience

**{current['officialTitle']}**

{current['company']} · {current['date']}

{experience}

## Skills in recommended order

1. Software Engineering
2. Developer Tooling
3. Python
4. C#
5. Azure DevOps
6. ASP.NET Core
7. Continuous Integration and Continuous Delivery (CI/CD)
8. .NET
9. REST APIs
10. Release Automation
11. Security Automation
12. SQL Server
13. PowerShell
14. Git
15. Application Authorization
16. Root Cause Analysis
17. FastAPI
18. Go

## Featured

- [Portfolio]({canonical})
- [{software['label']} (PDF)]({canonical}{software['file']})
{featured}

## Open to Work titles

1. Developer Productivity Engineer. The closest match for building tools that improve engineering workflows.
2. Software Engineer, Internal Tools. Fits application development, integrations, and workflow automation.
3. Developer Experience Engineer. Fits reusable tooling and checks that make delivery easier to navigate.
4. Platform Software Engineer. Prioritize teams building developer-facing software and release tooling.
5. Security Automation Engineer. Fits teams building discovery tooling, application controls, and safer pipelines.
6. Production Engineer. Prioritize openings centered on software development, diagnostics, and preventive automation.

## Technical post ideas

1. **Four kinds of release evidence.** Use a toy repository to show why inventory, build results, dry runs, and live deployment evidence answer different questions.
2. **From an overflow to a regression test.** Reproduce a numeric boundary failure with synthetic input and show how to select a test that catches it.
3. **Checking file-copy behavior before deployment.** Use disposable directories to demonstrate how a preflight check can protect files owned by the target environment.
4. **What a second reviewer can verify.** Use HowlProof to discuss reproducible evidence and how to report a check that could not run.
5. **Keep implementation and approval separate.** Use a public HowlPlane example to illustrate explicit action permissions and human review.

Use public examples or synthetic data for these posts.
"""


if __name__ == "__main__":
    data = json.loads((ROOT / "resume.json").read_text(encoding="utf-8"))
    variants = json.loads((ROOT / "resume_variants.json").read_text(encoding="utf-8"))
    destination = ROOT / "documentation" / "linkedin_profile.md"
    destination.parent.mkdir(exist_ok=True)
    destination.write_text(render_profile(data, variants), encoding="utf-8")
